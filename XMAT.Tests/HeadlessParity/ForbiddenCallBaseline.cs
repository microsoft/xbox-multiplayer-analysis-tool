using System.Globalization;
using System.Text;

namespace XMAT.Tests.HeadlessParity
{
    // The checked-in inventory of GUI-only API calls that existed in non-UI code before the headless work. It may
    // only shrink: delete a line (or lower its count) in the change that removes the call.
    internal static class ForbiddenCallBaseline
    {
        internal const string FileName = "ForbiddenCallBaseline.txt";

        private static readonly string[] Header =
        {
            "# Headless parity IL ratchet: GUI-only API calls from non-UI code (shrink-only).",
            "# Format: assembly|caller type::caller method|callee type::member|call sites",
            "# Generated by ForbiddenCallRatchetTests (XMAT_PARITY_IL_WRITE). Only ever delete lines or lower counts.",
        };

        internal static string DefaultPath =>
            Path.Combine(RepositoryPaths.Root, "XMAT.Tests", "HeadlessParity", FileName);

        internal static Dictionary<string, int> Load(string path)
        {
            var entries = new Dictionary<string, int>(StringComparer.Ordinal);
            string[] lines = File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
            for (int index = 0; index < lines.Length; index++)
            {
                string line = lines[index].Trim();
                if (line.Length == 0 || line.StartsWith("#", StringComparison.Ordinal))
                {
                    continue;
                }

                int separator = line.LastIndexOf('|');
                if (separator <= 0 ||
                    line.Substring(0, separator).Split('|').Length != 3 ||
                    !int.TryParse(line.Substring(separator + 1), NumberStyles.None, CultureInfo.InvariantCulture, out int count) ||
                    count <= 0)
                {
                    throw new FormatException($"{FileName} line {index + 1} is not 'assembly|caller|callee|count': {line}");
                }

                if (!entries.TryAdd(line.Substring(0, separator), count))
                {
                    throw new FormatException($"{FileName} line {index + 1} repeats an entry: {line}");
                }
            }

            return entries;
        }

        internal static void Write(string path, IEnumerable<ForbiddenCall> calls)
        {
            var text = new StringBuilder();
            foreach (string line in Header)
            {
                text.Append(line).Append("\r\n");
            }

            foreach (ForbiddenCall call in calls.OrderBy(call => call.Key, StringComparer.Ordinal))
            {
                text.Append(call.ToLine()).Append("\r\n");
            }

            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path)));
            File.WriteAllText(path, text.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        }
    }
}
